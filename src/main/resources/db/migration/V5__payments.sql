-- Step 5: online payments through a payment provider (a mock one in this project).
--
-- A user can no longer mark their own bill as paid. They start a payment; the bill becomes PAID only when the
-- provider confirms it through a signed webhook. Every attempt is a row here, so failed and expired attempts
-- stay visible.

create table payments (
    payment_id         bigint generated by default as identity,
    bill_id            bigint not null,
    user_id            bigint not null,
    amount             numeric(38, 2) not null,
    currency           varchar(3) not null,
    method             varchar(20) not null,
    status             varchar(20) not null,
    provider           varchar(20) not null,
    provider_reference varchar(64) not null,
    idempotency_key    varchar(100) not null,
    failure_reason     varchar(255),
    created_at         timestamp(6) not null,
    expires_at         timestamp(6) not null,
    completed_at       timestamp(6),
    updated_at         timestamp(6),
    -- Same NULL-ignoring guard pattern as V3/V4: bill id while PENDING, otherwise null, so a bill can have at
    -- most one payment in progress.
    active_bill_id     bigint,
    constraint pk_payments primary key (payment_id),
    constraint uk_payments_provider_reference unique (provider_reference),
    -- A client retrying with the same key gets the same payment instead of a second charge
    constraint uk_payments_user_idempotency_key unique (user_id, idempotency_key),
    constraint uk_payments_active_bill unique (active_bill_id),
    constraint ck_payments_status check (status in ('PENDING', 'SUCCEEDED', 'FAILED', 'EXPIRED', 'REFUND_REQUIRED')),
    constraint ck_payments_method check (method in ('CARD', 'UPI', 'NET_BANKING')),
    constraint fk_payments_bill foreign key (bill_id) references bills (bill_id),
    constraint fk_payments_user foreign key (user_id) references parking_user (user_id)
);

create index ix_payments_bill on payments (bill_id);
